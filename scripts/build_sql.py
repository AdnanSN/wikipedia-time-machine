#!/usr/bin/env python3
"""Turn the downloaded revisions into SQL that fills the `page` and `revision` tables.

    python scripts/build_sql.py               writes build/load_revisions.sql
    python scripts/build_sql.py --articles 3  only the first 3 articles in data/pages.tsv

run_all.sql sources the result. The SQL is generated rather than committed because it is
about 170 MB, while the compressed revision files it is made from are a few MB.
Uses only the Python standard library (3.9 or newer).
"""

import argparse
import json
import lzma
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PAGES = ROOT / "data" / "pages.tsv"
REVISIONS = ROOT / "data" / "revisions"
OUTPUT = ROOT / "build" / "load_revisions.sql"

BATCH_BYTES = 1_000_000  # well below the 16 MB default max_allowed_packet

# The escapes the MariaDB parser understands inside '...' when NO_BACKSLASH_ESCAPES is off,
# which the generated file makes sure of by setting sql_mode itself.
ESCAPES = str.maketrans({"\\": "\\\\", "'": "\\'", "\0": "\\0", "\n": "\\n",
                         "\r": "\\r", "\x1a": "\\Z"})


def sql_string(value):
    return "NULL" if value is None else "'" + value.translate(ESCAPES) + "'"


def sql_value(value):
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, int):
        return str(value)
    return sql_string(value)


def mediawiki_timestamp(iso):
    """'2009-11-04T12:34:56Z' -> '2009-11-04 12:34:56' (UTC, as Wikipedia stores it)."""
    return iso.replace("T", " ").rstrip("Z")


def revision_row(page_id, r):
    return "(" + ",".join(sql_value(v) for v in (
        r["rev_id"], page_id, r["parent_id"], mediawiki_timestamp(r["timestamp"]),
        r["minor"], r["user"], r["comment"], r["size"], r["sha1"],
        ",".join(r["tags"]) or None, r["deleted"], r["content"],
    )) + ")"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--articles", type=int, help="only the first N articles")
    args = parser.parse_args()

    lines = PAGES.read_text(encoding="utf-8").splitlines()
    header = lines[0].split("\t")
    pages = [dict(zip(header, line.split("\t"))) for line in lines[1:] if line]
    if args.articles:
        pages = pages[:args.articles]

    OUTPUT.parent.mkdir(exist_ok=True)
    total = 0
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as out:
        out.write("-- Generated by scripts/build_sql.py from data/revisions/. Do not edit.\n"
                  "SET NAMES utf8mb4;\n"
                  "SET SESSION sql_mode = 'STRICT_TRANS_TABLES,ERROR_FOR_DIVISION_BY_ZERO,"
                  "NO_ENGINE_SUBSTITUTION';\n"
                  "SET time_zone = '+00:00';\n"
                  "USE wiki_time_machine;\n\n")
        out.write("INSERT INTO page (page_id, page_title, page_latest) VALUES\n"
                  + ",\n".join(f"({int(p['page_id'])},{sql_string(p['title'])},"
                               f"{int(p['last_rev_id'])})" for p in pages) + ";\n\n")
        insert = ("INSERT INTO revision (rev_id, rev_page, rev_parent_id, rev_timestamp, "
                  "rev_minor_edit, rev_actor, rev_comment, rev_len, rev_sha1, rev_tags, "
                  "rev_deleted, content) VALUES\n")
        for page in pages:
            path = REVISIONS / f"{page['page_id']}.jsonl.xz"
            with lzma.open(path, "rt", encoding="utf-8") as f:
                records = [json.loads(line) for line in f]
            if len(records) != int(page["revisions"]):
                sys.exit(f"{path.name} has {len(records)} revisions, data/pages.tsv says "
                         f"{page['revisions']}: run scripts/fetch_revisions.py --check")
            batch, size = [], 0
            for r in records:
                row = revision_row(int(page["page_id"]), r)
                if batch and size + len(row) > BATCH_BYTES:
                    out.write(insert + ",\n".join(batch) + ";\n")
                    batch, size = [], 0
                batch.append(row)
                size += len(row)
            out.write(insert + ",\n".join(batch) + ";\n")
            total += len(records)
            print(f"{page['title']}: {len(records)} revisions", file=sys.stderr)
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(pages)} articles, {total} revisions",
          file=sys.stderr)


if __name__ == "__main__":
    main()
